/**
 * Reviewer sheets for the case library, generated from content/library/*.json so they never drift:
 * one page per case (docs/library/<id>.md), an index (docs/library/README.md) and the licence table
 * inside docs/CASE_LIBRARY.md (between the library:licences markers).
 *
 *   npm run library          regenerate everything
 *   npm run library:check    exit 1 if anything is stale or orphaned (tests/case-library.test.ts runs the same check)
 *
 * Output is deterministic (library order, no timestamps). † marks content added for realism (augmented).
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { byCategory, grounding, loadLibrary, type Grounding } from '../../content/library';
import type { LibraryCase, LibraryFinding } from '../../shared/caseLibrary';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const OUT_DIR = path.join(ROOT, 'docs', 'library');
export const GUIDE = path.join(ROOT, 'docs', 'CASE_LIBRARY.md');
const MARKER = '<!-- Generated by scripts/library/sheets.ts';
export const LIC_START = '<!-- library:licences:start (generated by `npm run library`; do not edit by hand) -->';
export const LIC_END = '<!-- library:licences:end -->';
const DAGGER = ' †';

/** escape authored text for markdown, also inside table cells */
const t = (s: string) => s.replace(/\|/g, '\\|').replace(/\*/g, '\\*').replace(/<(?=[A-Za-z/!])/g, '&lt;').replace(/\r?\n/g, ' ');
const cap = (s: string) => (s ? s[0].toUpperCase() + s.slice(1) : s);
const plural = (n: number, w: string) => `${n} ${w}${n === 1 ? '' : 's'}`;

function table(head: string[], rows: string[][]): string[] {
  if (!rows.length) return [];
  return [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map((x) => x || ' ').join(' | ')} |`), ''];
}

export function ageText(c: LibraryCase): string {
  const a = c.patient.age;
  const who = a < 18 ? (c.patient.sex === 'F' ? 'girl' : 'boy') : c.patient.sex === 'F' ? 'woman' : 'man';
  const months = c.patient.ageMonths ?? a * 12;
  if (months < 1) return `${Math.max(1, Math.round(months * 4.35))}-week-old ${who}`;
  if (a < 2) return `${Number(months.toFixed(1))}-month-old ${who}`;
  return `${a}-year-old ${who}`;
}

/** common analytes in both unit systems: `a` (conventional) × factor = `b` (SI), shown with dec decimals */
const CONVERSIONS: { name: RegExp; a: string; b: string; factor: number; decA: number; decB: number }[] = [
  { name: /glucose/i, a: 'mg/dL', b: 'mmol/L', factor: 0.0555, decA: 0, decB: 1 },
  { name: /creatinine(?! kinase)/i, a: 'mg/dL', b: 'µmol/L', factor: 88.4, decA: 2, decB: 0 },
  { name: /^urea\b/i, a: 'mg/dL', b: 'mmol/L', factor: 1 / 6.006, decA: 0, decB: 1 },
  { name: /^(bun|blood urea nitrogen)\b/i, a: 'mg/dL', b: 'mmol/L urea', factor: 0.357, decA: 0, decB: 1 },
  { name: /^(ha?emoglobin|hb|hgb)\b/i, a: 'g/dL', b: 'g/L', factor: 10, decA: 1, decB: 0 },
  { name: /albumin/i, a: 'g/dL', b: 'g/L', factor: 10, decA: 1, decB: 0 },
  { name: /calcium/i, a: 'mg/dL', b: 'mmol/L', factor: 0.2495, decA: 1, decB: 2 },
  { name: /bilirubin/i, a: 'mg/dL', b: 'µmol/L', factor: 17.1, decA: 1, decB: 0 },
  { name: /magnesium/i, a: 'mg/dL', b: 'mmol/L', factor: 0.4114, decA: 1, decB: 2 },
  { name: /phosph/i, a: 'mg/dL', b: 'mmol/L', factor: 0.3229, decA: 1, decB: 2 },
  { name: /(paracetamol|acetaminophen)/i, a: 'µg/mL', b: 'µmol/L', factor: 6.62, decA: 0, decB: 0 },
  { name: /(paracetamol|acetaminophen)/i, a: 'mg/L', b: 'µmol/L', factor: 6.62, decA: 0, decB: 0 },
  { name: /salicylate/i, a: 'mg/dL', b: 'mmol/L', factor: 0.0724, decA: 0, decB: 2 },
  { name: /digoxin/i, a: 'ng/mL', b: 'nmol/L', factor: 1.28, decA: 1, decB: 1 },
  { name: /ammonia/i, a: 'µg/dL', b: 'µmol/L', factor: 0.587, decA: 0, decB: 0 },
  { name: /ethanol|alcohol/i, a: 'mg/dL', b: 'mmol/L', factor: 0.217, decA: 0, decB: 1 },
  { name: /troponin/i, a: 'ng/mL', b: 'ng/L', factor: 1000, decA: 3, decB: 0 },
];
const unitKey = (u: string) => u.toLowerCase().replace(/\s+/g, '').replace(/[μu](?=g|mol)/g, 'µ');

/** the same result in the other unit system ("1.9 mg/dL" → "168 µmol/L"), or '' */
export function otherUnits(f: LibraryFinding): string {
  const m = f.value.trim().match(/^([<>≤≥]?)\s*(\d+(?:,\d{3})*(?:\.\d+)?)$/);
  if (!m || !f.unit) return '';
  const u = unitKey(f.unit);
  const v = Number(m[2].replace(/,/g, ''));
  for (const c of CONVERSIONS) {
    if (!c.name.test(f.name)) continue;
    if (u === unitKey(c.a)) return `${m[1]}${(v * c.factor).toFixed(c.decB)} ${c.b}`;
    if (u === unitKey(c.b)) return `${m[1]}${(v / c.factor).toFixed(c.decA)} ${c.a}`;
  }
  return '';
}

const dag = (g: Grounding, leaf: string) => (g.leaves.get(leaf)?.augmented && !g.leaves.get(leaf)?.evidence.length ? DAGGER : '');
const list = (xs: string[]) => (xs.length ? xs.map(t).join('; ') : '—');

export function renderCaseSheet(c: LibraryCase): string {
  const g = grounding(c);
  const s = c.source;
  const p = c.presentation;
  const augCount = [...g.leaves.values()].filter((x) => x.augmented).length;
  const out: string[] = [
    `${MARKER} from content/library/${c.id}.json; edit the JSON, then run \`npm run library\`. -->`,
    `# ${t(c.title)}`,
    '',
    ...table(['', ''], [
      ['Case', `\`${c.id}\``],
      ['Category · acuity', `${cap(c.category)} · ESI ${c.acuity}`],
      ['Patient', `${ageText(c)}${c.patient.arrival ? `, ${c.patient.arrival}` : ''}`],
      ['Source', `[${t(s.citation)}](${s.url})`],
      ['Identifiers', [s.pmcid && `PMCID ${s.pmcid}`, s.pmid && `PMID ${s.pmid}`, s.doi && `DOI [${s.doi}](https://doi.org/${s.doi})`].filter(Boolean).join(' · ')],
      ['Licence', s.license],
      ['Grounding', `${plural(c.evidence.length, 'quote')} · ${augCount} augmented item${augCount === 1 ? '' : 's'} (marked †)`],
    ]),
    '## Vignette',
    '',
    `**Chief complaint:** ${t(p.chiefComplaint)}`,
    '',
    `**History:** ${t(p.hpi)}${g.leaves.get('presentation.hpi')?.notes.length ? ` *(augmented: ${t(g.leaves.get('presentation.hpi')!.notes.join('; '))})*` : ''}`,
    '',
  ];
  const listLine = (label: string, k: 'pmh' | 'meds' | 'allergies') =>
    `- **${label}:** ${p[k].length ? p[k].map((x, i) => t(x) + dag(g, `presentation.${k}[${i}]`)).join('; ') : '—'}`;
  out.push(listLine('Past history', 'pmh'), listLine('Medications', 'meds'), listLine('Allergies', 'allergies'));
  if (p.social) out.push(`- **Social:** ${t(p.social)}${dag(g, 'presentation.social')}`);
  if (p.family) out.push(`- **Family:** ${t(p.family)}${dag(g, 'presentation.family')}`);
  const v = c.vitals;
  const vt = (k: keyof typeof v, x: string) => x + dag(g, `vitals.${k}`);
  out.push('', '## Vitals on arrival', '', ...table(['HR', 'BP', 'RR', 'SpO₂', 'Temp', 'GCS'], [[
    vt('hr', `${v.hr}/min`),
    `${v.sbp}${dag(g, 'vitals.sbp')}/${v.dbp}${dag(g, 'vitals.dbp')} mm Hg`,
    vt('rr', `${v.rr}/min`),
    vt('spo2', `${v.spo2}%`),
    vt('tempC', `${v.tempC.toFixed(1)} °C (${((v.tempC * 9) / 5 + 32).toFixed(1)} °F)`),
    v.gcs === undefined ? '—' : vt('gcs', String(v.gcs)),
  ]]));
  out.push('## Examination', '', ...c.exam.map((x, i) => `- ${t(x)}${dag(g, `exam[${i}]`)}`), '');
  out.push('## Investigations', '', ...table(['Test', 'Result', 'Unit', 'Flag', 'Other units'], c.investigations.map((f, i) => [
    t(f.name) + dag(g, `investigations[${i}]`), t(f.value), t(f.unit ?? ''), f.flag ? (f.flag === 'critical' ? '**critical**' : f.flag) : '', otherUnits(f),
  ])));
  if (c.imaging?.length) out.push('## Imaging', '', ...c.imaging.map((im, i) => `- **${t(im.modality)}:** ${t(im.finding)}${dag(g, `imaging[${i}]`)}`), '');
  if (c.ecg) out.push('## ECG', '', t(c.ecg) + dag(g, 'ecg'), '');
  out.push('## Diagnosis', '', `**${t(c.diagnosis.primary)}**${c.diagnosis.icd10 ? ` (ICD-10-CM ${c.diagnosis.icd10})` : ''}`, '', `Differentials: ${list(c.diagnosis.differentials)}`, '');
  out.push('## Management', '', ...c.management.map((x, i) => `${i + 1}. ${t(x)}${dag(g, `management[${i}]`)}`), '');
  if (c.outcome) out.push('## Outcome', '', t(c.outcome), '');
  out.push('## Teaching points', '', ...c.teachingPoints.map((x) => `- ${t(x)}`), '');
  out.push('## Quiz questions', '');
  c.questions.forEach((q, i) => {
    out.push(`### Q${i + 1} · ${q.kind}`, '', t(q.q), '');
    if (q.extra) out.push(`> ${t(q.extra)}`, '');
    q.options.forEach((o, j) => out.push(j === q.answer ? `- **${'ABCD'[j]}. ${t(o)}** ✓` : `- ${'ABCD'[j]}. ${t(o)}`));
    out.push('', `*Why:* ${t(q.explanation)}`, '');
  });
  out.push('## Evidence (quoted from the source)', '', ...table(['#', 'Field', 'Quote'], c.evidence.map((e, i) => [String(i + 1), `\`${e.field.replace(/\|/g, '\\|')}\``, `“${t(e.quote)}”`])));
  const inline = [...c.investigations.filter((f) => f.augmented).map((f) => t(f.name)), ...(c.imaging ?? []).filter((im) => im.augmented).map((im) => t(im.modality))];
  out.push('## Augmented for realism (not in the source)', '');
  for (const a of c.augmented) out.push(`- ${t(a).replace(/^([^:]+)(:\s|$)/, '`$1`$2')}`);
  if (inline.length) out.push(`- Results flagged inline: ${inline.join('; ')}`);
  if (!c.augmented.length && !inline.length) out.push('- Nothing');
  out.push('');
  return out.join('\n');
}

export function renderIndex(cases: LibraryCase[]): string {
  const groups = byCategory(cases);
  const sources = new Set(cases.map((c) => c.source.pmcid ?? c.source.doi));
  const out = [
    `${MARKER} from content/library/*.json; run \`npm run library\` after editing a case. -->`,
    '# Case library: reviewer sheets',
    '',
    `${plural(cases.length, 'case')} from ${plural(sources.size, 'open-access source')}, one page each for clinical review. Rules, workflow and licences: [docs/CASE_LIBRARY.md](../CASE_LIBRARY.md). † on a sheet marks content added for realism (not in the source).`,
    '',
    '## By category',
    '',
    ...table(['Category', 'Cases', 'ESI 1', 'ESI 2', 'ESI 3', 'ESI 4–5'], [...groups].map(([cat, xs]) => [
      cap(cat), String(xs.length), ...[1, 2, 3].map((a) => String(xs.filter((c) => c.acuity === a).length)), String(xs.filter((c) => c.acuity >= 4).length),
    ])),
    '## Cases',
    '',
  ];
  for (const [cat, xs] of groups) {
    out.push(`### ${cap(cat)}`, '', ...table(['Case', 'Patient', 'ESI', 'Diagnosis', 'Source', 'Licence'], xs.map((c) => [
      `[${t(c.title)}](${c.id}.md)`, ageText(c), String(c.acuity), t(c.diagnosis.primary), `[${c.source.pmcid ?? c.source.doi}](${c.source.url})`, c.source.license,
    ])));
  }
  return out.join('\n');
}

/** the licence table that lives between LIC_START and LIC_END in docs/CASE_LIBRARY.md */
export function renderLicenceBlock(cases: LibraryCase[]): string {
  const byLicence = new Map<string, number>();
  for (const c of cases) byLicence.set(c.source.license, (byLicence.get(c.source.license) ?? 0) + 1);
  return [
    LIC_START,
    '',
    `${plural(cases.length, 'case')}: ${[...byLicence].sort().map(([l, n]) => `${n} × ${l}`).join(', ')}.`,
    '',
    ...table(['Case', 'Source', 'Licence', 'Link'], cases.map((c) => [`\`${c.id}\``, t(c.source.citation), c.source.license, c.source.url])),
    LIC_END,
  ].join('\n');
}

/** docs/CASE_LIBRARY.md with its licence block replaced, or undefined if the guide or its markers are missing */
export function renderGuide(cases: LibraryCase[], current = existsSync(GUIDE) ? readFileSync(GUIDE, 'utf8') : undefined): string | undefined {
  if (current === undefined) return undefined;
  const a = current.indexOf(LIC_START);
  const b = current.indexOf(LIC_END);
  if (a < 0 || b < a) return undefined;
  return current.slice(0, a) + renderLicenceBlock(cases) + current.slice(b + LIC_END.length);
}

/** file name in docs/library → contents */
export function renderAll(cases: LibraryCase[] = loadLibrary({ fresh: true })): Map<string, string> {
  const out = new Map<string, string>();
  for (const c of cases) out.set(`${c.id}.md`, renderCaseSheet(c));
  out.set('README.md', renderIndex(cases));
  return out;
}

/** problems that `npm run library` would fix (empty when everything is current) */
export function checkLibrarySheets(): string[] {
  const cases = loadLibrary({ fresh: true });
  const want = renderAll(cases);
  const problems: string[] = [];
  for (const [f, md] of want) {
    const file = path.join(OUT_DIR, f);
    if (!existsSync(file)) problems.push(`missing docs/library/${f}`);
    else if (readFileSync(file, 'utf8') !== md) problems.push(`stale docs/library/${f}`);
  }
  if (existsSync(OUT_DIR)) for (const f of readdirSync(OUT_DIR)) if (f.endsWith('.md') && !want.has(f)) problems.push(`orphaned docs/library/${f}`);
  const guide = renderGuide(cases);
  if (guide === undefined) problems.push('docs/CASE_LIBRARY.md is missing or lacks the library:licences markers');
  else if (guide !== readFileSync(GUIDE, 'utf8')) problems.push('stale licence table in docs/CASE_LIBRARY.md');
  return problems;
}

export function writeLibrarySheets(): string[] {
  const cases = loadLibrary({ fresh: true });
  const want = renderAll(cases);
  mkdirSync(OUT_DIR, { recursive: true });
  const changed: string[] = [];
  for (const f of readdirSync(OUT_DIR)) {
    if (f.endsWith('.md') && !want.has(f) && readFileSync(path.join(OUT_DIR, f), 'utf8').startsWith(MARKER)) { rmSync(path.join(OUT_DIR, f)); changed.push(`removed docs/library/${f}`); }
  }
  for (const [f, md] of want) {
    const file = path.join(OUT_DIR, f);
    if (!existsSync(file) || readFileSync(file, 'utf8') !== md) { writeFileSync(file, md); changed.push(`wrote docs/library/${f}`); }
  }
  const guide = renderGuide(cases);
  if (guide !== undefined && guide !== readFileSync(GUIDE, 'utf8')) { writeFileSync(GUIDE, guide); changed.push('updated licence table in docs/CASE_LIBRARY.md'); }
  if (guide === undefined) changed.push('WARNING: docs/CASE_LIBRARY.md is missing or lacks the licence markers');
  return changed;
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  if (process.argv.includes('--check')) {
    const problems = checkLibrarySheets();
    for (const p of problems) console.log(p);
    if (problems.length) { console.log('\nRun `npm run library` to regenerate.'); process.exit(1); }
    console.log('Case library sheets are up to date.');
  } else {
    const changed = writeLibrarySheets();
    console.log(changed.length ? changed.join('\n') : 'Case library sheets already up to date.');
  }
}
