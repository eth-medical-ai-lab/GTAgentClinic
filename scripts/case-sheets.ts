/** a case's bed position (content/types.ts CaseBedDef), in words */
function bedText(b: CaseBedDef): string {
  const one = (x: Omit<CaseBedDef, 'afterOrders' | 'symptomatic'>) =>
    [x.sitting === 'edge' ? `on the stretcher's edge (backrest ${x.headDeg}°)` : `head of the bed ${x.headDeg}°`, x.sitting === 'upright' ? 'sitting up' : '', x.knees ? 'knees bent' : '', x.legUp ? `${x.legUp === 'R' ? 'right' : 'left'} leg raised on a pillow` : ''].filter(Boolean).join(', ');
  const parts = [one(b)];
  if (b.symptomatic) parts.push(`${b.symptomatic.headDeg}° while the observed ${b.symptomatic.var.toUpperCase()} is ${b.symptomatic.op} ${b.symptomatic.value}`);
  if (b.afterOrders) parts.push(`once ${b.afterOrders.codes.map(code).join(' or ')} is done: ${one(b.afterOrders.bed)}`);
  return parts.join('; ');
}

