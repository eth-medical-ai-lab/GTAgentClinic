function itemsBlock(x: CaseCtx): string[] {
  const raw = (x.c as { items?: unknown }).items;
  if (raw === undefined) return [];
  if (!Array.isArray(raw)) return ['### Belongings / inspectable items', '', ...genericBlock('items', raw)];
  const items = raw as CaseItemDef[];
  const rows = items.map((it) => {
    const facts = (it.facts ?? []).map((id) => {
      const f = x.facts.get(id);
      if (!f) {
        x.warnings.push(`item ${code(it.id)} reveals unknown fact ${code(id)}`);
        return `${code(id)} (no such fact)`;
      }
      return `${f.fact.key ? '★ ' : ''}${code(id)} ${t(f.fact.label ?? '')} *(${t(f.source)})*`;
    });
    const available = it.arrivesWith === 'family' ? `when ${t(x.c.family?.name ?? 'family')} is there${x.c.family?.arrivesAtMin !== undefined ? ` (+${x.c.family.arrivesAtMin} min)` : ' (from arrival)'}` : 'from arrival';
    return [`**${t(it.label)}**<br>${code(it.id)}`, t(kindWords(String(it.kind))), t(WHERE[it.where] ?? String(it.where)), available, `${t(it.text)}${more(it, K.item)}`, facts.join('<br>') || '—'];
  });
  return [
    '### Belongings / inspectable items',
    '',
    'Inspecting an item shows its text; the listed facts then count as elicited history, exactly as if asked.',
    '',
    ...table(['Item', 'Kind', 'Where', 'Available', 'Inspecting shows', 'Counts as history'], rows),
  ];
}

function keyHistoryBlock(x: CaseCtx): string[] {
  const { c } = x;
  const groups = new Map<string, string[]>();
  const add = (f: FactDef, source: string) => {
    if (!f.key) return;
    const label = keyLabel(f);
    groups.set(label, [...(groups.get(label) ?? []), `${t(source)} ${code(f.id)}`]);
  };
  for (const f of c.persona.facts) add(f, 'patient');
  for (const f of c.family?.persona.facts ?? []) add(f, familyWho(c));
  for (const pc of c.phoneContacts ?? []) for (const f of pc.persona.facts) add(f, `phone: ${pc.contact.name}`);
  const items = Array.isArray((c as { items?: unknown }).items) ? (c.items ?? []) : [];
  for (const it of items)
    for (const id of it.facts ?? []) {
      const f = x.facts.get(id)?.fact;
      if (f?.key) groups.get(keyLabel(f))?.push(`inspect ${code(it.id)}`);
    }
  if (!groups.size) return ['### Key history (scored)', '', `No key facts: the ${c.scoring.historyPoints} history points cannot be earned.`, ''];
  const each = c.scoring.historyPoints / groups.size;
  return [
    '### Key history (scored)',
    '',
    `${c.scoring.historyPoints} points split over ${plural(groups.size, 'item')} (≈ ${num(each, 1)} each). Facts sharing a label count once, whoever tells it.`,
    '',
    ...table(
      ['Scored item', 'Get it from'],
      [...groups.entries()].map(([label, from]) => [t(cap(label)), from.join(' · ')]),
    ),
  ];
}

function historySection(x: CaseCtx): string[] {
  const { c } = x;
  const refs = ruleRefs(c);
  const L: string[] = ['## Who knows what', '', '★ = scored key history. Facts are first-person lines the NPC can say when asked a matching question (keywords not shown).', ''];
  L.push(...personaBlock(x, `Patient: ${t(patientName(c))}`, c.patient.voice ? [`voice ${code(c.patient.voice.id)}${c.patient.voice.speed ? ` ×${c.patient.voice.speed}` : ''}`] : [], c.persona, refs.counseling));
  if (c.family) {
    const f = c.family;
    const meta = [f.arrivesAtMin === undefined ? 'at the bedside from arrival' : `arrives ${f.arrivesAtMin} min after the patient`];
    if (f.voice) meta.push(`voice ${code(f.voice.id)}${f.voice.speed ? ` ×${f.voice.speed}` : ''}`);
    L.push(...personaBlock(x, `Family at the bedside: ${t(f.name)}, ${t(f.relation)}`, meta, f.persona, refs.counseling), ...otherFields(f, K.family, 'family'));
  }
  for (const pc of c.phoneContacts ?? []) L.push(...phoneBlock(x, pc, refs.counseling));
  L.push(...itemsBlock(x), ...keyHistoryBlock(x));
  return L;
}

function examSection(x: CaseCtx): string[] {
  const { c } = x;
  const ids = [...EXAM_MANEUVERS.map((m) => m.id).filter((id) => id in c.exam), ...Object.keys(c.exam).filter((id) => !EXAM_BY_ID[id]).sort()];
  const rows = ids.map((id) => {
    const m = EXAM_BY_ID[id];
    if (!m) x.warnings.push(`exam maneuver ${code(id)} is not in the catalog (shared/catalog.ts → EXAM_MANEUVERS), so players can never perform it`);
    const v = c.exam[id];
    let text: string;
    if (typeof v === 'string') text = t(v);
    else if (Array.isArray(v))
      text = v
        .map((variant) => {
          const w = variant.when;
          const rest = more(variant, ['text', 'when']);
          return w ? `**If ${varLabel(w.var)} ${w.op} ${withUnit(w.var, num(w.value))}:** ${t(variant.text)}${rest}` : `**Otherwise:** ${t(variant.text)}${rest}`;
        })
        .join('<br>');
    else text = inline(v);
    return [t(m?.system ?? '?'), `${t(m?.label ?? id)}${m?.chaperone ? ' (chaperone)' : ''}<br>${code(id)}`, text];
  });
  const missing = c.provenance.kind === 'adapted' ? 'Unlisted maneuvers have no recorded finding.' : 'Other maneuvers use the catalog normal.';
  return ['## Exam findings', '', `${missing} Variants are checked top to bottom against current physiology.`, '', ...table(['System', 'Maneuver', 'Finding'], rows)];
}

function physiologySection(x: CaseCtx): string[] {
  const { c, proj } = x;
  const ph = c.physiology;
  const L: string[] = ['## Physiology', ''];
  const shownVars = PHYS_VARS.filter((pv) => ph.baseline[pv.v] !== undefined || ph.drift?.[pv.v] !== undefined || ph.limits?.[pv.v] !== undefined);
  L.push(
    ...table(
      ['Variable', 'Baseline', 'Drift / h (untreated)', 'Limits', 'Noise SD'],
      shownVars.map((pv) => [
        `${pv.label}${pv.unit ? ` (${pv.unit})` : ''}`,
        ph.baseline[pv.v] !== undefined ? num(ph.baseline[pv.v]!, 2) : '(default)',
        ph.drift?.[pv.v] ? signed(ph.drift[pv.v]!) : '',
        ph.limits?.[pv.v] ? `${num(ph.limits[pv.v]![0])}–${num(ph.limits[pv.v]![1])}` : '',
        ph.noise?.[pv.v] !== undefined ? num(ph.noise[pv.v]!) : '',
      ]),
    ),
  );

  // untreated course
  const changing = PHYS_VARS.filter((pv) => ['hr', 'sbp', 'dbp', 'rr', 'spo2', 'temp'].includes(pv.v) || COURSE_TIMES.some((m) => Math.abs(proj.value(pv.v, m) - proj.value(pv.v, 0)) > 1e-6));
  const cols = changing.filter((pv) => pv.v !== 'dbp');
  const rows = COURSE_TIMES.map((m, i) => {
    const firedNow = proj.fired.filter((f) => f.minute <= m && (i === 0 || f.minute > COURSE_TIMES[i - 1])).map((f) => code(f.tr.id));
    return [
      m === 0 ? 'arrival' : `${m} min`,
      ...cols.map((pv) => (pv.v === 'sbp' ? `${num(proj.value('sbp', m), 0)}/${num(proj.value('dbp', m), 0)}` : num(proj.value(pv.v, m), pv.dec))),
      firedNow.join(', '),
    ];
  });
  L.push('### Untreated course', '', 'Noise-free values from the sim engine if nobody intervenes (triggers included).', '');
  L.push(...table(['t', ...cols.map((pv) => (pv.v === 'sbp' ? 'BP' : pv.label)), 'Triggers fired'], rows));
  const notFired = (ph.triggers ?? []).filter((tr) => !proj.fired.some((f) => f.tr.id === tr.id));
  const firedTxt = proj.fired.map((f) => `${code(f.tr.id)} at +${num(f.minute, 1)} min`);
  if (ph.triggers?.length)
    L.push(`Untreated trigger times: ${firedTxt.length ? firedTxt.join(' · ') : 'none'}${notFired.length ? `; not reached within ${proj.horizon / 60} h: ${notFired.map((tr) => code(tr.id)).join(', ')}` : ''}.`, '');

  // treatment effects
  L.push('### Treatment effects', '');
  L.push(`Δ is the full effect per dose (per liter for fluids), reached with ramp time constant τ after the onset delay. "Lasts" effects fade out over 30 min afterwards; others persist. Drift × multiplies the untreated drift once active: 0 stops it, negative reverses it (recovery).`, '');
  const effRows = ph.effects.map((e: EffectDef) => {
    const src = tagSources(x, e.tag);
    if (!src.length) x.warnings.push(`physiology effect ${code(e.tag)} can never apply: no catalog drug, nursing order or consult applies that tag`);
    const delta = Object.entries(e.delta ?? {}).map(([v, d]) => `${varLabel(v)} ${signed(d as number)}`);
    const drift = Object.entries(e.driftMult ?? {}).map(([v, d]) => `${varLabel(v)} ×${num(d as number)}`);
    const notes: string[] = [];
    if (e.maxUnits !== undefined) notes.push(e.tag === 'fluids' ? `counts ≤ ${e.maxUnits} L` : `≤ ${e.maxUnits} doses count`);
    if (e.harm) notes.push(`**harm** ${code(e.harm.flag)}${e.harm.chance !== undefined ? ` (${Math.round(e.harm.chance * 100)}%)` : ''}${e.harm.page ? `: nurse pages ${quote(e.harm.page)}` : ''}`);
    return [
      code(e.tag),
      src.join('<br>') || '⚠ nothing applies this tag',
      e.onsetMin !== undefined ? `${num(e.onsetMin)} min` : '0',
      `${num(e.tauMin ?? 10)} min`,
      e.durationMin !== undefined ? `${num(e.durationMin)} min` : 'persists',
      delta.join(', ') || '—',
      drift.join(', ') || '—',
      `${notes.join('<br>')}${more(e, K.effect)}`,
    ];
  });
  L.push(...table(['Tag', 'Given by', 'Onset', 'τ', 'Lasts', 'Δ at full effect', 'Drift ×', 'Notes'], effRows));
  if (!ph.effects.length) L.push('*No treatment effects defined.*', '');

  // triggers
  if (ph.triggers?.length) {
    L.push('### Triggers', '');
    L.push(
      ...table(
        ['Trigger', 'When', 'Page', 'Then'],
        ph.triggers.map((tr) => {
          const then: string[] = [];
          if (tr.flag) then.push(`flag ${code(tr.flag)}`);
          if (tr.driftAdd) then.push(`drift ${Object.entries(tr.driftAdd).map(([v, d]) => `${varLabel(v)} ${signed(d as number)}/h`).join(', ')}`);
          if (tr.jump) then.push(`jump ${Object.entries(tr.jump).map(([v, d]) => `${varLabel(v)} ${signed(d as number)}`).join(', ')}`);
          if (tr.emotion) then.push(`patient looks ${tr.emotion}`);
          return [code(tr.id), whenText(tr.when), tr.page ? `${tr.page.priority} from ${tr.page.from}: ${quote(tr.page.text)}` : '—', `${then.join('<br>') || '—'}${more(tr, K.trigger)}`];
        }),
      ),
    );
  }
  const known = PHYS_VARS.map((pv) => pv.v as string);
  for (const [name, part] of [['baseline', ph.baseline], ['drift', ph.drift], ['limits', ph.limits], ['noise', ph.noise]] as const) L.push(...otherFields(part, known, `physiology ${name}`));
  L.push(...otherFields(ph, K.physiology, 'physiology'));
  return L;
}

function labsSection(x: CaseCtx): string[] {
  const { c, proj } = x;
  const sex = c.patient.sex;
  const L: string[] = ['## Labs', ''];
  const codes = Object.keys(c.labs);
  const missing = c.provenance.kind === 'adapted' ? 'Unlisted results are unavailable.' : 'Unlisted results use simulated reference values.';
  if (!codes.length) {
    L.push(`*No case-specific lab values.* ${missing}`, '');
    return L;
  }
  L.push(`Values in conventional units with the catalog reference range; **bold** = flagged (H/L, HH/LL critical). Physiology-linked values are shown at arrival and on the untreated course. ${missing} Repeat draws of static numeric values vary ±1.5%.`, '');
  const ordersFor = (a: string) =>
    ORDER_LIST.filter((o) => o.category === 'lab' && o.analytes?.includes(a))
      .map((o) => `${code(o.code)} ${o.tatMin ? span(o.tatMin) : ''}`.trim())
      .join(' · ');
  const fmt = (a: string, v: number | string) => {
    const dec = ANALYTES[a]?.decimals ?? 1;
    const val = typeof v === 'number' ? Math.round(v * 10 ** dec) / 10 ** dec : v;
    const shown = typeof val === 'number' ? (ANALYTES[a] ? formatLabValue(a, val, 'US') : num(val, 3)) : t(val);
    const flag = ANALYTES[a] ? computeFlag(a, val, sex) : undefined;
    return { val, text: flag ? `**${shown}**${flag === 'A' ? '' : ` ${flag}`}` : shown };
  };
  const at = (truth: LabTruth, m: number): number | string | undefined => {
    if (typeof truth === 'number' || typeof truth === 'string') return truth;
    if (truth && typeof truth === 'object' && 'var' in truth) return proj.value(truth.var, m);
    if (truth && typeof truth === 'object' && 'kind' in truth && (truth.kind === 'sigmoid' || truth.kind === 'series')) return curveAt(truth, m);
    return undefined;
  };
  const course = (a: string, truth: LabTruth): string => {
    if (typeof truth !== 'object' || truth === null) return '';
    const times = 'var' in truth ? [60, 120, 240] : truth.kind === 'sigmoid' ? [60, 120, 180, 240, 360, 720] : truth.points.map((p) => p[0]).filter((m) => m > 0);
    const pts = times.map((m) => `${fmt(a, at(truth, m)!).text} (${m % 60 === 0 ? `${m / 60} h` : `${m} min`})`);
    if ('var' in truth) return times.every((m) => Math.abs(proj.value(truth.var, m) - proj.value(truth.var, 0)) < 1e-6) ? `<br>tracks ${code(truth.var)} (stable untreated)` : `<br>tracks ${code(truth.var)}; untreated: ${pts.join(' → ')}`;
    if (truth.kind === 'sigmoid') return `<br>rises: ${pts.join(' → ')}<br>*logistic ${num(truth.base)} → ${num(truth.peak)}, 50% at ${num(truth.t50Min)} min, width ${num(truth.widthMin)} min*`;
    return `<br>then ${pts.join(' → ')} (linear between points)`;
  };
  const sections = new Map<string, string[][]>();
  const ordered = [...Object.keys(ANALYTES).filter((a) => a in c.labs), ...codes.filter((a) => !ANALYTES[a]).sort()];
  for (const a of ordered) {
    const def = ANALYTES[a];
    if (!def) x.warnings.push(`lab analyte ${code(a)} is not in the catalog (shared/catalog.ts → ANALYTES), so no order can result it`);
    const truth = c.labs[a];
    const v0 = at(truth, 0);
    let result: string;
    let si = '';
    if (v0 === undefined) result = inline(truth);
    else {
      const f = fmt(a, v0);
      result = `${f.text}${course(a, truth)}`;
      if (def && typeof f.val === 'number' && def.unitSI !== undefined && (def.unitSI !== def.unit || (def.toSI ?? 1) !== 1)) si = `${formatLabValue(a, f.val, 'SI')} ${labUnit(a, 'SI')}`;
    }
    const ref = def ? `${refRangeText(a, sex, 'US')}${def.unit && !def.text ? ` ${def.unit}` : ''}` : '';
    const via = ordersFor(a);
    if (def && !via) x.warnings.push(`lab value ${code(a)} (${t(def.name)}) is never shown: no catalog lab order returns that analyte`);
    const section = def?.section ?? 'Not in catalog';
    sections.set(section, [...(sections.get(section) ?? []), [`${t(def?.name ?? a)}<br>${code(a)}`, result, t(ref), t(si), via || '⚠ no order returns it']]);
  }
  for (const [section, rows] of sections) L.push(`### ${section}`, '', ...table(['Test', 'Result', 'Reference', 'SI', 'Ordered as (turnaround)'], rows));
  return L;
}

function imagingSection(x: CaseCtx): string[] {
  const { c } = x;
  const ids = [...ORDER_LIST.filter((o) => o.code in c.imaging).map((o) => o.code), ...Object.keys(c.imaging).filter((id) => !ORDERS[id]).sort()];
  const L: string[] = ['## Imaging', '', c.provenance.kind === 'legacy' ? 'Studies not listed here return a normal report.' : 'Unlisted studies have no report available.', ''];
  for (const id of ids) {
    const o = ORDERS[id];
    if (!o) x.warnings.push(`imaging code ${code(id)} is not in the catalog, so it can never be ordered`);
    const im = c.imaging[id];
    L.push(`**${t(o?.name ?? id)}** ${code(id)}${o?.modality ? ` · ${o.modality}${o.contrast ? ' with contrast' : ''}` : ''}${o && !im.blocked ? ` · ${orderTiming(o)}` : ''}`, '');
    if (im.blocked) L.push(`- **Refused** by ${t(im.blocked.from)} (order canceled after 3–6 min): ${quote(im.blocked.message)}`);
    if (im.findings) L.push(`- **Findings:** ${t(im.findings)}`);
    if (im.impression) L.push(`- **Impression:** ${t(im.impression)}`);
    if (im.criticalCall) L.push(`- **Radiologist phones:** ${quote(im.criticalCall)}`);
    const rest = more(im, K.imaging);
    if (rest) L.push(`- ${rest.slice(3)}`);
    L.push('');
  }
  if (!ids.length) L.push('*No case-specific imaging.*', '');
  return L;
}

/** bedside ultrasound (CaseDef.pocus): every window, the case's read (variants top to bottom) or normal */
function pocusSection(x: CaseCtx): string[] {
  const { c } = x;
  const rows: string[][] = [];
  const unlisted = c.provenance.kind === 'adapted' ? 'No recorded finding' : 'Normal (simulated baseline)';
  for (const w of POCUS_WINDOWS) {
    const raw = c.pocus?.[w.id];
    const list = raw ? (Array.isArray(raw) ? raw : [raw]) : [];
    if (!list.length) {
      rows.push([t(w.label), unlisted, '']);
      continue;
    }
    for (const v of list) {
      const when = !v.when ? (list.length > 1 ? 'otherwise' : '') : 'flag' in v.when ? `flag ${code(v.when.flag)}` : `${v.when.var} ${v.when.op} ${v.when.value}`;
      rows.push([t(w.label), t(v.text), when]);
    }
  }
  if (!c.pocus) return ['## Bedside ultrasound (POCUS)', '', `All windows: ${unlisted}.`, ''];
  return ['## Bedside ultrasound (POCUS)', '', 'The read per view (exam maneuver `pocus_<window>`, in the Examine tab; `{rate}` is the heart rate now). Not scored.', '', ...table(['Window', 'Read', 'When'], rows)];
}

const LEADS = ['I', 'II', 'III', 'aVR', 'aVL', 'aVF', 'V1', 'V2', 'V3', 'V4', 'V5', 'V6', 'V4R'];

const RHYTHMS: Record<string, string> = { sinus: 'sinus', afib: 'atrial fibrillation', flutter: 'atrial flutter', svt: 'SVT', vt: 'ventricular tachycardia', vf: 'ventricular fibrillation', asystole: 'asystole', paced: 'paced' };

function ecgParamsText(p: CaseDef['ecg']['params']): string[][] {
  const rows: string[][] = [['Rhythm', `${t(RHYTHMS[p.rhythm] ?? String(p.rhythm))} (${code(p.rhythm)}), rate ${p.rate}/min`]];
  const iv = [p.pr !== undefined ? `PR ${p.pr} ms` : '', p.qrs !== undefined ? `QRS ${p.qrs} ms` : '', p.qt !== undefined ? `QT ${p.qt} ms` : ''].filter(Boolean);
  if (iv.length) rows.push(['Intervals', iv.join(' · ')]);
  if (p.axis !== undefined) rows.push(['Axis', `${p.axis}°`]);
  const st = Object.entries(p.st ?? {}).sort((a, b) => LEADS.indexOf(a[0]) - LEADS.indexOf(b[0]));
  rows.push(['ST deviation', st.length ? st.map(([lead, mm]) => `${lead} ${signed(mm as number, 1)} mm`).join(' · ') : 'none']);
  if (p.tInversion?.length) rows.push(['T inversion', p.tInversion.join(', ')]);
  if (p.qWaves?.length) rows.push(['Q waves', p.qWaves.join(', ')]);
  if (p.peakedT) rows.push(['Peaked T', 'yes']);
  const dev = [p.rightSided ? 'right-sided leads' : '', p.noise !== undefined ? `noise ${p.noise}` : '', p.seed !== undefined ? `seed ${p.seed}` : ''].filter(Boolean);
  const rest = more(p, K.ecgParams);
  if (dev.length || rest) rows.push(['Renderer', `${dev.join(' · ')}${rest}`]);
  return rows;
}

function ecgSection(x: CaseCtx): string[] {
  const e = x.c.ecg;
  const L: string[] = ['## ECG', ''];
  if (e.unavailable) return [...L, 'No ECG tracing is available for this encounter.', ''];
  L.push(e.autoAtMin !== undefined ? `Acquired automatically by triage protocol at **+${e.autoAtMin} min**; otherwise on order (${code('ecg12')}).` : `Only on order (${code('ecg12')}); no protocol ECG.`, '');
  L.push(...table(['', ''], [...ecgParamsText(e.params), ['Machine read', t(e.machineRead)], ['Correct physician read contains any of', e.readKeywords.map(code).join(' · ')]]));
  if (e.rightSided) {
    L.push(`**Right-sided ECG** (${code('ecg_right')}):`, '', ...table(['', ''], [...ecgParamsText(e.rightSided.params), ['Machine read', t(e.rightSided.machineRead)]]));
    L.push(...otherFields(e.rightSided, ['params', 'machineRead'], 'right-sided ECG'));
  }
  L.push(...otherFields(e, K.ecg, 'ECG'));
  return L;
}

function consultsSection(x: CaseCtx): string[] {
  const { c } = x;
  const all = [...Object.values(SCENARIOS).flatMap((s) => s.internalContacts), ...(resolveScenario(practiceId(c.id), 0)?.internalContacts ?? INTERNAL_CONTACTS), ...(c.phoneContacts ?? [])];
  const L: string[] = ['## Consults', ''];
  if (!c.consults.length) L.push('*No case-specific consults.*', '');
  for (const cd of c.consults) {
    const k = all.find((pc) => pc.contact.id === cd.contactId)?.contact;
    L.push(`### ${k ? `${t(k.role)}: ${t(k.name)}` : t(cd.contactId)} ${code(cd.contactId)}${k ? ` · ${t(k.phone)}` : ''}`, '');
    L.push(`- **Accepts when** (told to the LLM consultant): ${t(cd.criteria)}`);
    L.push(`- **Server guard:** ${cd.guard ? describeRule(cd.guard, ruleNames(x)) : 'none (the consultant decides)'}`);
    const a = cd.onAccept;
    const acc: string[] = [];
    if (a.dispo) acc.push(`disposition “${dispoLabel(a.dispo)}”${a.service ? ` (${t(a.service)})` : ''}`);
    if (a.tag) acc.push(`applies ${code(a.tag)}${a.tagAfterMin ? ` after ${a.tagAfterMin} min` : ' immediately'}`);
    if (a.departAfterMin !== undefined) acc.push(`patient leaves the ED after ${a.departAfterMin} min`);
    if (a.page) acc.push(`page: ${quote(a.page)}`);
    if (a.note) acc.push(`consult note **${t(a.note.title)}**: ${t(a.note.text)}`);
    L.push(`- **On accept:** ${acc.length ? acc.join('; ') : 'nothing (advice only)'}${more(a, K.onAccept)}`);
    L.push(`- **When declining:** ${t(cd.declineHint)}`, '');
    L.push(...otherFields(cd, K.consult, 'consult'));
  }
  return L;
}

function ruleRefs(c: CaseDef): RuleRefs {
  const refs: RuleRefs = { orders: new Set(), tags: new Set(), maneuvers: new Set(), contacts: new Set(), facts: new Set(), counseling: new Set(), flags: new Set() };
  for (const k of c.scoring.critical) collectRefs(k.rule, refs);
  for (const h of c.scoring.harms) collectRefs(h.rule, refs);
  for (const cd of c.consults) collectRefs(cd.guard, refs);
  return refs;
}

function scoringSection(x: CaseCtx): string[] {
  const { c } = x;
  const sc = c.scoring;
  const names = ruleNames(x);
  const secondary = (sc.secondaryDx ?? []).reduce((s, d) => s + d.points, 0);
  const critical = sc.critical.reduce((s, k) => s + k.points, 0);
  const conditional = sc.critical.filter((k) => k.rule.type === 'if').reduce((s, k) => s + k.points, 0);
  const max = sc.dxPoints + secondary + sc.dispoPoints + sc.historyPoints + critical;
  const L: string[] = ['## Scoring rubric', ''];
  L.push(
    `**Max ${max} points:** diagnosis ${sc.dxPoints}${secondary ? ` (+${secondary} secondary)` : ''} · disposition ${sc.dispoPoints} · key history ${sc.historyPoints} · critical actions ${critical}${conditional ? ` (${conditional} only when applicable)` : ''}. Harms and low-value orders subtract. Time windows count from the patient’s arrival.`,
    '',
  );
  L.push('### Critical actions', '');
  L.push(...table(['Action', 'Pts', 'Rule', 'Teaching'], sc.critical.map((k) => [`${t(k.label)} ${code(k.id)}${more(k, K.critical)}`, String(k.points), describeRule(k.rule, names), t(k.teaching ?? '')])));
  L.push('### Harms', '');
  if (sc.harms.length) L.push(...table(['Harm', 'Penalty', 'Rule', 'Teaching'], sc.harms.map((h) => [`${t(h.label)} ${code(h.id)}${more(h, K.harm)}`, `${MINUS}${h.penalty}`, describeRule(h.rule, names), t(h.teaching)])));
  else L.push('*None defined.*', '');
  L.push('### Low-value orders', '');
  if (sc.lowValue.length)
    L.push(
      ...table(
        ['Orders', 'Penalty', 'Why'],
        sc.lowValue.map((lv) => [lv.codes.map((cd) => `${code(cd)} ${t(orderName(cd))}`).join('<br>'), `${MINUS}${lv.penalty}`, `${t(lv.why)}${more(lv, ['codes', 'penalty', 'why'])}`]),
      ),
      'Penalties apply once per row if any listed order is placed by the player (protocol and attending orders, and orders canceled within 5 min before collection, are exempt).',
      '',
    );
  else L.push('*None defined.*', '');
  L.push('### Disposition', '');
  L.push(`- Best (${sc.dispoPoints} pts): ${c.truth.dispositions.map(dispoLabel).join(' / ')}`);
  if (c.truth.acceptableDispositions?.length) L.push(`- Acceptable (${Math.round(sc.dispoPoints / 2)} pts): ${c.truth.acceptableDispositions.map(dispoLabel).join(' / ')}`);
  L.push('- Anything else, or none by the end of the shift: 0', '');

  // legend
  const refs = ruleRefs(c);
  const rows: string[][] = [];
  for (const o of [...refs.orders].sort()) {
    if (!ORDERS[o]) x.warnings.push(`rule references unknown order code ${code(o)}`);
    rows.push([code(o), `${t(orderName(o))}${ORDERS[o] && orderTiming(ORDERS[o]) ? ` (${orderTiming(ORDERS[o])})` : ''}`]);
  }
  for (const tag of [...refs.tags].sort()) {
    const meds = MEDS_BY_TAG.get(tag) ?? [];
    if (!meds.length) x.warnings.push(`rule references drug tag ${code(tag)} that no catalog drug carries`);
    rows.push([code(tag), meds.length ? [...new Set(meds.map(medPhrase))].map(t).join('; ') : 'no catalog drug carries this tag']);
  }
  for (const m of [...refs.maneuvers].sort()) {
    if (!EXAM_BY_ID[m]) x.warnings.push(`rule references unknown exam maneuver ${code(m)}`);
    rows.push([code(m), `exam: ${t(examLabel(m))}`]);
  }
  for (const k of [...refs.contacts].sort()) rows.push([code(k), `phone: ${t(x.contacts.get(k) ?? 'unknown contact')}`]);
  for (const f of [...refs.facts].sort()) {
    const fr = x.facts.get(f);
    if (!fr) x.warnings.push(`rule references unknown fact ${code(f)}`);
    rows.push([code(f), fr ? `fact from ${t(fr.source)}: ${t(fr.fact.label ?? fr.fact.text)}` : 'unknown fact']);
  }
  for (const ci of [...refs.counseling].sort()) {
    if (!x.counseling.has(ci)) x.warnings.push(`rule references unknown counseling item ${code(ci)}`);
    rows.push([code(ci), `counseling: ${t(x.counseling.get(ci) ?? 'unknown')}`]);
  }
  for (const fl of [...refs.flags].sort()) rows.push([code(fl), `flag: ${x.flags.get(fl) ?? 'set by the engine or a scenario'}`]);
  if (rows.length) L.push('### Codes used in these rules', '', ...table(['Code', 'Meaning'], rows));
  L.push(...otherFields(sc, K.scoring, 'scoring'));
  return L;
}

function renderCase(x: CaseCtx): string {
  const { c } = x;
  x.warnings = [];
  const L: string[] = [header(x.file), '', `# ${t(c.title)}`, ''];
  L.push(`> **One-liner:** ${t(c.summary)}`, '');
  L.push(`${code(c.id)} · difficulty ${c.difficulty}/3 · ${patientName(c)}, ${c.patient.age} ${c.patient.sex} · ${t(c.presentation.chiefComplaint)} · ${c.presentation.arrivalMode} · ESI ${c.presentation.esi}`, '');
  L.push(...appearsIn(x));
  const p = c.provenance;
  L.push('## Provenance', '', `- **Origin:** ${p.kind} · **Author:** ${t(authorLabel(p))} · **Clinical review:** ${t(reviewLabel(p))}`,
    `- **Specialty:** ${t(c.specialty)} · **Record:** [${t(p.file)}](../../${p.file})`, `- **Method:** ${t(p.method)}`);
  if (p.kind === 'adapted') L.push(`- **Source:** ${t(p.dataset)} · ${code(p.recordId)} · [${t(p.source.citation)}](${p.source.url}) · ${t(p.source.license)}`);
  L.push('');
  L.push(...truthSection(x), ...presentationSection(x), ...historySection(x));
  const details = [...examSection(x), ...physiologySection(x), ...labsSection(x), ...imagingSection(x), ...pocusSection(x), ...ecgSection(x), ...consultsSection(x), ...scoringSection(x)];
  L.push(...details);
  L.push('## Teaching points', '', ...c.teaching.map((s, i) => `${i + 1}. ${t(s)}`), '');
  L.push('## References', '', ...c.references.map((s, i) => `${i + 1}. ${t(s)}`), '');
  const other = otherFields(c, K.case, 'case');
  if (other.length) L.push('## Other fields', '', ...other);
  for (const s of x.slots)
    for (const f of x.proj.fired)
      if (!('var' in f.tr.when) && s.arriveAtMin + f.minute > s.sc.durationMin)
        x.warnings.push(`trigger ${code(f.tr.id)} (${whenText(f.tr.when)}) can never fire on ${t(s.sc.title)}: it is due at shift minute ${num(s.arriveAtMin + f.minute, 1)}, after the shift ends at ${s.sc.durationMin}`);
  if (x.warnings.length) L.push('## Content checks', '', ...[...new Set(x.warnings)].map((w) => `- ⚠ ${w}`), '');
  return `${L.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

