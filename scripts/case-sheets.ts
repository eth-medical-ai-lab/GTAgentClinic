function vitalsLine(v: Vitals): string {
  const parts: string[] = [];
  if (v.hr !== undefined) parts.push(`HR ${v.hr}`);
  if (v.sbp !== undefined && v.dbp !== undefined) parts.push(`BP ${v.sbp}/${v.dbp} (MAP ${Math.round((v.sbp + 2 * v.dbp) / 3)})`);
  if (v.rr !== undefined) parts.push(`RR ${v.rr}`);
  if (v.spo2 !== undefined) parts.push(`SpO₂ ${v.spo2}%${v.o2 ? ` ${t(v.o2)}` : ''}`);
  parts.push(v.temp !== undefined ? `T ${num(v.temp, 1)} °C (${num((v.temp * 9) / 5 + 32, 1)} °F)` : 'T not recorded');
  if (v.pain !== undefined) parts.push(`pain ${v.pain}/10`);
  if (v.gcs !== undefined) parts.push(`GCS ${v.gcs}`);
  if (v.glucose !== undefined) parts.push(`glucose ${v.glucose} mg/dL (${num(v.glucose * 0.0555, 1)} mmol/L)`);
  for (const [k, val] of extras(v, ['hr', 'sbp', 'dbp', 'rr', 'spo2', 'temp', 'pain', 'gcs', 'glucose', 'o2'])) parts.push(`${t(k)} ${inline(val)}`);
  return parts.join(' · ');
}

