// ───────────────────────────── markdown helpers ─────────────────────────────

/** escape authored free text for markdown (also safe inside table cells) */
function t(s: string): string {
  return s
    .replace(/\|/g, '\\|')
    .replace(/\*/g, '\\*')
    .replace(/<(?=[A-Za-z/!])/g, '&lt;')
    .replace(/\r?\n/g, '<br>');
}

/** code span; spaces at the edges are made visible because they matter for substring matching */
function code(s: string): string {
  return `\`${s.replace(/^ +| +$/g, (m) => '␣'.repeat(m.length)).replace(/\|/g, '\\|')}\``;
}

const quote = (s: string) => `“${t(s)}”`;

function table(head: string[], rows: string[][]): string[] {
  if (!rows.length) return [];
  return [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map((x) => x || ' ').join(' | ')} |`), ''];
}

function orList(xs: string[], word = 'or'): string {
  if (xs.length <= 1) return xs[0] ?? '';
  return `${xs.slice(0, -1).join(', ')} ${word} ${xs[xs.length - 1]}`;
}

function num(n: number, dec = 2): string {
  const s = String(Number(n.toFixed(dec)));
  return s.startsWith('-') ? MINUS + s.slice(1) : s;
}

const signed = (n: number, dec = 2) => (n > 0 ? `+${num(n, dec)}` : num(n, dec));
const plural = (n: number, w: string) => `${n} ${w}${n === 1 ? '' : 's'}`;
const cap = (s: string) => (s ? s[0].toUpperCase() + s.slice(1) : s);

function span(r: [number, number]): string {
  return r[0] >= 120 && r[0] % 60 === 0 && r[1] % 60 === 0 ? `${r[0] / 60}–${r[1] / 60} h` : `${r[0]}–${r[1]} min`;
}

function clock(start: string, min: number): string {
  const [h, m] = start.split(':').map(Number);
  const total = (((h * 60 + m + Math.round(min)) % 1440) + 1440) % 1440;
  return `${String(Math.floor(total / 60)).padStart(2, '0')}:${String(total % 60).padStart(2, '0')}`;
}

const rel = (min: number) => (min < 0 ? `${MINUS}${num(-min, 1)} min` : `+${num(min, 1)} min`);

/** GitHub heading anchor */
const anchor = (heading: string) => heading.toLowerCase().replace(/[^a-z0-9 _-]/g, '').trim().replace(/ /g, '-');

// ── unknown / future fields: rendered generically so new schema fields show up instead of vanishing ──

function inline(v: unknown, depth = 0): string {
  if (v === undefined || v === null) return '—';
  if (typeof v === 'string') return t(v);
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (Array.isArray(v)) return v.length ? v.map((x) => inline(x, depth + 1)).join('; ') : '(none)';
  if (typeof v === 'object') {
    if (depth > 4) return '…';
    return Object.entries(v as Record<string, unknown>)
      .filter(([, x]) => x !== undefined)
      .map(([k, x]) => `${k}: ${inline(x, depth + 1)}`)
      .join(', ');
  }
  return t(String(v));
}

function extras(o: unknown, known: readonly string[]): [string, unknown][] {
  if (!o || typeof o !== 'object' || Array.isArray(o)) return [];
  return Object.entries(o as Record<string, unknown>).filter(([k, v]) => !known.includes(k) && v !== undefined);
}

/** " · key: value" suffix for unknown fields of a row-sized record */
function more(o: unknown, known: readonly string[]): string {
  return extras(o, known)
    .map(([k, v]) => ` · *${t(k)}:* ${inline(v)}`)
    .join('');
}

function genericBlock(key: string, v: unknown): string[] {
  if (Array.isArray(v) && v.length && v.every((x) => x && typeof x === 'object' && !Array.isArray(x))) {
    const rows = v as Record<string, unknown>[];
    const cols: string[] = [];
    for (const row of rows) for (const k of Object.keys(row)) if (!cols.includes(k)) cols.push(k);
    return [`**${t(key)}**`, '', ...table(cols.map(t), rows.map((row) => cols.map((k) => inline(row[k]))))];
  }
  if (v && typeof v === 'object' && !Array.isArray(v)) {
    return [`**${t(key)}**`, '', ...Object.entries(v as Record<string, unknown>).map(([k, x]) => `- ${t(k)}: ${inline(x)}`), ''];
  }
  return [`- **${t(key)}:** ${inline(v)}`, ''];
}

/** block for unknown fields of a section (nothing if there are none) */
function otherFields(o: unknown, known: readonly string[], where: string): string[] {
  const ex = extras(o, known);
  if (!ex.length) return [];
  return [`*Other ${where} fields (rendered generically; teach scripts/case-sheets.ts about them):*`, '', ...ex.flatMap(([k, v]) => genericBlock(k, v))];
}

