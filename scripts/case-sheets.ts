/** optional names that make rule text friendlier; everything still renders without them */
export interface RuleNames {
  contacts?: ReadonlyMap<string, string>;
  counseling?: ReadonlyMap<string, string>;
  /** flag → where it gets set ("trigger b_shock: SBP < 80 mmHg") */
  flags?: ReadonlyMap<string, string>;
}

/** Plain-English rendering of the scoring/guard rule DSL (content/types.ts → Rule; semantics: server/sim/scoring.ts). */
export function describeRule(rule: Rule, names: RuleNames = {}): string {
  const within = (m?: number) => (m === undefined ? '' : ` within ${m} min of arrival`);
  const codes = (cs: string[]) => orList(cs.map(code));
  const sub = (r: Rule) => (['any', 'all', 'if', 'before', 'not'].includes(r.type) ? `(${describeRule(r, names)})` : describeRule(r, names));
  const contact = (id: string) => (names.contacts?.get(id) ? `${code(id)} (${t(names.contacts.get(id)!)})` : code(id));
  const counsel = (id: string) => (names.counseling?.get(id) ? `${code(id)} (${t(names.counseling.get(id)!)})` : code(id));
  switch (rule.type) {
    case 'order':
      return `order ${codes(rule.codes)}${within(rule.withinMin)}`;
    case 'given': {
      const what = [...(rule.tags ?? []).map(tagPhrase), ...(rule.codes ?? []).map(code)];
      const amount = rule.minTotalMl !== undefined ? `≥ ${rule.minTotalMl} mL total of ` : '';
      return `given ${amount}${orList(what) || '(nothing specified)'}${within(rule.withinMin)}`;
    }
    case 'collected':
      return `collected ${codes(rule.codes)}${rule.count && rule.count > 1 ? ` ×${rule.count}` : ''}${within(rule.withinMin)}`;
    case 'before':
      return `${sub(rule.first)} BEFORE ${sub(rule.then)}`;
    case 'consult':
      return `${contact(rule.contactId)} accepts${within(rule.withinMin)}`;
    case 'escalated':
      return 'asked the attending for help with this patient';
    case 'called':
      return `phoned ${orList(rule.contactIds.map(contact))}`;
    case 'fact':
      return `elicited ${rule.all ? 'all' : 'any'} of ${rule.factIds.map(code).join(', ')}`;
    case 'counseled':
      return `counseled ${orList(rule.ids.map(counsel), rule.all ? 'and' : 'or')}`;
    case 'exam': {
      const n = rule.min ?? rule.maneuvers.length;
      return `examined ${n >= rule.maneuvers.length ? (rule.maneuvers.length === 1 ? '' : 'all of ') : `≥ ${n} of `}${rule.maneuvers.map(code).join(', ')}`;
    }
    case 'ecg_signed':
      return `ECG reviewed and signed${within(rule.withinMin)}`;
    case 'ecg_read':
      return 'ECG signed with a correct interpretation (matches the read keywords)';
    case 'vitals':
      return `vitals incl. ${rule.vars.join(', ')} recorded${within(rule.withinMin)}`;
    case 'dispo':
      return `disposition ${orList(rule.decisions.map((d) => `“${dispoLabel(d)}”`))}`;
    case 'dx':
      return `diagnosis mentions ${orList(rule.keywords.map(code))}`;
    case 'flag':
      if (rule.flag === '__never__') return 'never (this consultant cannot accept)';
      return `flag ${code(rule.flag)}${names.flags?.get(rule.flag) ? ` (${names.flags.get(rule.flag)})` : ''}`;
    case 'not':
      return `NOT ${sub(rule.rule)}`;
    case 'any':
      return rule.rules.map(sub).join(' OR ');
    case 'all':
      return rule.rules.map(sub).join(' AND ');
    case 'if':
      return `if ${sub(rule.cond)}: ${sub(rule.then)} (otherwise not scored)`;
    default: {
      const r = rule as { type?: unknown };
      return `${t(String(r.type ?? 'rule'))} {${inline(Object.fromEntries(Object.entries(r).filter(([k]) => k !== 'type')))}}`;
    }
  }
}

interface RuleRefs {
  orders: Set<string>;
  tags: Set<string>;
  maneuvers: Set<string>;
  contacts: Set<string>;
  facts: Set<string>;
  counseling: Set<string>;
  flags: Set<string>;
}

function collectRefs(rule: Rule | undefined, refs: RuleRefs): RuleRefs {
  if (!rule) return refs;
  switch (rule.type) {
    case 'order':
    case 'collected':
      rule.codes.forEach((c) => refs.orders.add(c));
      break;
    case 'given':
      rule.tags?.forEach((x) => refs.tags.add(x));
      rule.codes?.forEach((c) => refs.orders.add(c));
      break;
    case 'before':
      collectRefs(rule.first, refs);
      collectRefs(rule.then, refs);
      break;
    case 'consult':
      refs.contacts.add(rule.contactId);
      break;
    case 'called':
      rule.contactIds.forEach((c) => refs.contacts.add(c));
      break;
    case 'fact':
      rule.factIds.forEach((f) => refs.facts.add(f));
      break;
    case 'counseled':
      rule.ids.forEach((x) => refs.counseling.add(x));
      break;
    case 'exam':
      rule.maneuvers.forEach((m) => refs.maneuvers.add(m));
      break;
    case 'flag':
      if (rule.flag !== '__never__') refs.flags.add(rule.flag);
      break;
    case 'not':
      collectRefs(rule.rule, refs);
      break;
    case 'any':
    case 'all':
      rule.rules.forEach((r) => collectRefs(r, refs));
      break;
    case 'if':
      collectRefs(rule.cond, refs);
      collectRefs(rule.then, refs);
      break;
  }
  return refs;
}

// ───────────────────────────── engine mirrors ─────────────────────────────

interface Projection {
  /** noise-free value, minutes since arrival, nobody intervening */
  value(v: PhysVar, minute: number): number;
  fired: { tr: TriggerDef; minute: number }[];
  horizon: number;
}

/** Untreated course from the real physiology engine; triggers checked every 30 s like GameSession.processPatients(). */
function projectUntreated(c: CaseDef, horizon: number): Projection {
  const ph = new Physiology(c.physiology, `case-sheet:${c.id}`);
  const pending = [...(c.physiology.triggers ?? [])];
  const fired: { tr: TriggerDef; minute: number }[] = [];
  for (let m = 0; m <= horizon && pending.length; m += 0.5) {
    for (const tr of [...pending]) {
      const w = tr.when;
      const fire = 'var' in w ? (w.op === '<' ? ph.value(w.var, m) < w.value : ph.value(w.var, m) > w.value) : m >= w.afterMin;
      if (!fire) continue;
      ph.fireTrigger(tr, m);
      fired.push({ tr, minute: m });
      pending.splice(pending.indexOf(tr), 1);
    }
  }
  return { value: (v, m) => ph.value(v, m), fired, horizon };
}

/** mirrors GameSession.labValue() for curve-shaped lab truth (server/sim/session.ts) */
function curveAt(cv: CurveDef, minute: number): number {
  if (cv.kind === 'sigmoid') return cv.base + (cv.peak - cv.base) / (1 + Math.exp(-(minute - cv.t50Min) / cv.widthMin));
  const pts = cv.points;
  if (minute <= pts[0][0]) return pts[0][1];
  if (minute >= pts[pts.length - 1][0]) return pts[pts.length - 1][1];
  let i = 0;
  while (pts[i + 1][0] < minute) i++;
  const [x0, y0] = pts[i];
  const [x1, y1] = pts[i + 1];
  return y0 + ((y1 - y0) * (minute - x0)) / (x1 - x0);
}

