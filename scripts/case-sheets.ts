function errorRow(sc: ScenarioDef, e: StaffErrorDef, ctxs: Map<string, CaseCtx>): string[] {
  const who = (caseId: string) => {
    const x = ctxs.get(caseId);
    const slot = sc.patients.find((p) => p.caseId === caseId);
    return `${x ? t(patientName(x.c)) : code(caseId)}${slot ? ` (${t(bedLabel(sc, slot.bed))})` : ''}`;
  };
  let patient: string;
  let what: string;
  switch (e.kind) {
    case 'missing_triage_vital':
      patient = who(e.caseId);
      what = `Triage vitals are recorded without ${e.vital === 'temp' ? 'a temperature' : e.vital.toUpperCase()} at arrival.`;
      break;
    case 'abx_before_cultures':
      patient = who(e.caseId);
      what = 'When an antibiotic is about to be hung before blood cultures are drawn, the nurse announces it and gives it unless told to draw cultures first.';
      break;
    case 'wrong_patient_med':
      patient = `${who(e.wrongCaseId)}, meant for ${who(e.intendedCaseId)}`;
      what = `At ${clock(sc.shiftStart, e.atMin)} (+${e.atMin} min) ${t(staffName(sc, e.nurseId))} brings ${t(ORDERS[e.medCode]?.med?.generic ?? e.medCode)} ${t(e.dose)} ${t(e.route)} (${t(e.orderedBy)}) to the wrong patient; ${e.windowMin} min to stop it.`;
      break;
    default: {
      const g = e as { caseId?: string; kind?: string };
      patient = g.caseId ? who(g.caseId) : '';
      what = inline(Object.fromEntries(Object.entries(e).filter(([k]) => !['id', 'label', 'points', 'teaching'].includes(k))));
    }
  }
  return [`${code(e.id)}<br>${t(String(e.kind))}`, patient, what, t(e.label), String(e.points), t(e.teaching)];
}

function renderMap(sc: ScenarioDef, ctxs: Map<string, CaseCtx>): string[] {
  const end = clock(sc.shiftStart, sc.durationMin);
  const L: string[] = [`## ${t(sc.title)}`, ''];
  L.push(`${code(sc.id)} · *${t(sc.subtitle)}* · difficulty ${sc.difficulty} · shift ${sc.shiftStart}–${end} (${sc.durationMin} min) · default time ×${sc.defaultTimeScale} · layout ${code(sc.layoutId)}`, '');
  L.push(`> ${t(sc.description)}`, '');
  L.push('**Learning goals**', '', ...sc.learningGoals.map((g) => `- ${t(g)}`), '');

  // patients
  const slots = [...sc.patients].sort((a, b) => a.arriveAtMin - b.arriveAtMin);
  L.push('### Patients', '');
  L.push(
    ...table(
      ['Arrives', 'Bed', 'Patient', 'Case', 'ESI', 'Nurse'],
      slots.map((p) => {
        const x = ctxs.get(p.caseId);
        const c = x?.c;
        const nurse = sc.staff.find((s) => s.id === p.nurseId);
        return [
          `${clock(sc.shiftStart, p.arriveAtMin)} (${rel(p.arriveAtMin)})${p.arriveAtMin < 0 ? '<br>already waiting' : ''}`,
          t(bedLabel(sc, p.bed)),
          c ? `**${t(patientName(c))}**, ${c.patient.age} ${c.patient.sex}: ${t(c.presentation.chiefComplaint)} (${c.presentation.arrivalMode})` : '⚠ unknown case',
          c ? `[${code(c.id)}](${c.id}.md)<br>${t(c.truth.diagnosis.label)}` : code(p.caseId),
          c ? String(c.presentation.esi) : '',
          `${t(nurse?.name ?? p.nurseId)}${nurse ? `<br>*${t(nurse.title)}*` : ''}${more(p, K.slot)}`,
        ];
      }),
    ),
  );

  // timeline
  type Ev = { min: number; text: string };
  const ev: Ev[] = [];
  for (const i of sc.intro) ev.push({ min: 0, text: `Intro message from ${t(i.from)}: ${quote(i.text)}` });
  for (const p of slots) {
    const c = ctxs.get(p.caseId)?.c;
    if (!c) continue;
    const bed = bedLabel(sc, p.bed);
    const missing = sc.errors.find((e) => e.kind === 'missing_triage_vital' && e.caseId === p.caseId);
    ev.push({
      min: p.arriveAtMin,
      text: `**Arrival:** ${t(patientName(c))}, ${c.patient.age} ${c.patient.sex}, ${t(c.presentation.chiefComplaint)}, to ${t(bed)} (${arrivesBy(c.presentation.arrivalMode)}, ESI ${c.presentation.esi})${missing && missing.kind === 'missing_triage_vital' ? `; triage set lacks ${missing.vital === 'temp' ? 'a temperature' : missing.vital} (${code(missing.id)})` : ''}`,
    });
    if (c.ecg.autoAtMin !== undefined) ev.push({ min: Math.max(0, p.arriveAtMin + c.ecg.autoAtMin), text: `Protocol ECG acquired for ${t(c.patient.lastName)} (${t(bed)})` });
    if (c.family?.arrivesAtMin !== undefined) {
      const carried = (Array.isArray(c.items) ? c.items : []).filter((it) => it.arrivesWith === 'family');
      ev.push({ min: p.arriveAtMin + c.family.arrivesAtMin, text: `Family arrives: ${t(c.family.name)}, ${t(c.family.relation.toLowerCase())}, for ${t(bed)}${carried.length ? `, bringing ${carried.map((it) => t(it.label)).join(', ')}` : ''}` });
    }
  }
  for (const e of sc.events) {
    const who = e.npcId ? staffName(sc, e.npcId) : (e.from ?? '');
    const kind = e.kind === 'page' ? `Page${e.priority ? ` (${e.priority})` : ''}` : e.kind === 'bark' ? 'Overheard' : e.kind === 'rounds' ? 'Rounds' : cap(e.kind);
    ev.push({ min: e.atMin, text: `${kind}${who ? ` from ${t(who)}` : ''}: ${quote(e.text)}${more(e, K.event)}` });
  }
  for (const e of sc.errors) if (e.kind === 'wrong_patient_med') ev.push({ min: e.atMin, text: `**Staff error ${code(e.id)}:** ${t(staffName(sc, e.nurseId))} is about to give ${t(e.dose)} ${t(ORDERS[e.medCode]?.med?.generic ?? e.medCode)} meant for ${t(ctxs.get(e.intendedCaseId)?.c.patient.lastName ?? e.intendedCaseId)} to ${t(ctxs.get(e.wrongCaseId)?.c.patient.lastName ?? e.wrongCaseId)} (${e.windowMin} min to stop it)` });
  ev.push({ min: sc.durationMin, text: '**Shift ends**; patients without a disposition are scored as still in the ED' });
  ev.sort((a, b) => a.min - b.min);
  L.push('### Timeline', '', ...table(['Clock', 'Min', 'Event'], ev.map((e) => [clock(sc.shiftStart, e.min), rel(e.min), e.text])));

  // staff errors
  L.push('### Staff errors to catch', '');
  if (sc.errors.length) L.push(...table(['Error', 'Patient', 'What happens', 'Credit for', 'Pts', 'Teaching'], sc.errors.map((e) => errorRow(sc, e, ctxs))));
  else L.push('*None on this map.*', '');

  // untreated deterioration
  const det: { min: number; row: string[] }[] = [];
  const afterEnd: string[] = [];
  const notReached: string[] = [];
  for (const p of slots) {
    const x = ctxs.get(p.caseId);
    if (!x) continue;
    for (const f of x.proj.fired) {
      const shiftMin = p.arriveAtMin + f.minute;
      const label = `${code(f.tr.id)} ${whenText(f.tr.when)}`;
      if (shiftMin > sc.durationMin) afterEnd.push(`${t(x.c.patient.lastName)} ${label} (due at shift minute ${num(shiftMin, 1)})`);
      else det.push({ min: shiftMin, row: [clock(sc.shiftStart, shiftMin), rel(Math.round(shiftMin)), `${t(x.c.patient.lastName)} (${t(bedLabel(sc, p.bed))})`, label, f.tr.page ? `${f.tr.page.priority} page${f.tr.flag ? `, flag ${code(f.tr.flag)}` : ''}` : f.tr.flag ? `flag ${code(f.tr.flag)}` : ''] });
    }
    for (const tr of x.c.physiology.triggers ?? []) if (!x.proj.fired.some((f) => f.tr.id === tr.id)) notReached.push(`${t(x.c.patient.lastName)} ${code(tr.id)} ${whenText(tr.when)} (not within ${num(x.proj.horizon / 60, 1)} h)`);
  }
  det.sort((a, b) => a.min - b.min);
  L.push('### If nobody intervenes', '', 'Untreated trigger times from the physiology engine; treatment delays or averts them.', '');
  L.push(...table(['Clock', 'Min', 'Patient', 'Trigger', 'Effect'], det.map((d) => d.row)));
  if (!det.length) L.push('*No deterioration trigger fires during this shift when untreated.*', '');
  if (afterEnd.length) L.push(`Due after the shift ends, so they can never fire on this map: ${afterEnd.join(' · ')}.`, '');
  if (notReached.length) L.push(`Not reached untreated: ${notReached.join(' · ')}.`, '');

  // staff
  const nurses = sc.staff.filter((s) => s.role === 'nurse');
  L.push(`**Nurses:** ${nurses.map((n) => `${t(n.name)} (${t(n.title)})`).join(' · ')}`, '');
  const others = sc.staff.filter((s) => s.role !== 'nurse' && s.talkable);
  if (others.length) L.push(`**Other staff you can talk to:** ${others.map((n) => `${t(n.name)} (${t(n.title)})`).join(' · ')}`, '');
  L.push(`**Phone directory:** ${sc.internalContacts.map((pc) => `${code(pc.contact.id)} ${t(pc.contact.name)} (${t(pc.contact.phone)})`).join(' · ')}`, '');
  L.push(...otherFields(sc, K.scenario, 'scenario'));
  return L;
}

