// ───────────────────────────── index ─────────────────────────────

const ABBREVIATIONS = new Set(['vs', 'e.g', 'i.e', 'dr', 'al', 'approx', 'cf', 'fig', 'no', 'mr', 'mrs', 'ms', 'st']);

function firstSentence(s: string): string {
  const re = /[.!?]\s+(?=\S)/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(s))) {
    const word = /([A-Za-z.]+)$/.exec(s.slice(0, m.index))?.[1] ?? '';
    if (ABBREVIATIONS.has(word.toLowerCase()) || /^[A-Z]$/.test(word) || word.includes('.')) continue;
    return s.slice(0, m.index + 1);
  }
  return s;
}

/** short form of a teaching point for the index: its first sentence, without asides if too long, cut at a natural break */
function brief(s: string, max = 110): string {
  let first = firstSentence(s.trim());
  if (first.length <= max) return first.replace(/[.;:]$/, '');
  for (let prev = ''; prev !== first; ) [prev, first] = [first, first.replace(/\s*\([^()]*\)/g, '')];
  if (first.length <= max) return first.replace(/[.;:]$/, '');
  let depth = 0;
  let cut = -1;
  for (let i = 0; i < max; i++) {
    const ch = first[i];
    if (ch === '(') depth++;
    else if (ch === ')') depth = Math.max(0, depth - 1);
    else if (depth === 0 && i >= 25 && [' — ', '; ', ': ', ', '].some((d) => first.startsWith(d, i))) cut = i;
  }
  if (cut > 0) return `${first.slice(0, cut)}…`;
  let end = first.lastIndexOf(' ', max);
  const open = first.lastIndexOf(' (', end);
  if (open > 0 && first.indexOf(')', open) > end) end = open;
  return `${first.slice(0, end).replace(/[,;:]$/, '')}…`;
}

function renderIndex(ctxs: CaseCtx[]): string {
  const L: string[] = [header('content/ (all cases and maps)'), '', '# Case sheets', ''];
  L.push(
    'Readable clinical case files for development, generated from the playable registry by `scripts/case-sheets.ts`. Do not edit them by hand:',
    '',
    '- `npm run cases` regenerates them after you change a case, a map or the catalog.',
    '- `npm run cases:check` exits non-zero when they are stale; `npm test` runs the same check.',
    '',
    'Every case can be played individually or drawn in a mixed shift. Each sheet includes its provenance, hidden truth, history, exam, physiology, investigations, scoring and teaching. Fixed shift assignments are in [maps.md](maps.md).',
    '',
  );
  const rows = ctxs.map((x) => {
    const c = x.c;
    const maps = x.slots.length
      ? x.slots.map((s) => `[${t(s.sc.title)}](maps.md#${anchor(s.sc.title)}): ${t(bedLabel(s.sc, s.bed))}, ${clock(s.sc.shiftStart, s.arriveAtMin)} (${rel(s.arriveAtMin)})`).join('<br>')
      : 'Assigned at arrival';
    return [
      `[**${t(c.title)}**](${c.id}.md)<br>${code(c.id)} · ${c.patient.age} ${c.patient.sex} · ${t(c.presentation.chiefComplaint)}`,
      `${t(c.truth.diagnosis.label)} (${t(c.truth.diagnosis.icd10)})`,
      String(c.presentation.esi),
      maps,
      c.teaching.map((s) => `• ${t(brief(s))}`).join('<br>'),
    ];
  });
  L.push(...table(['Case', 'Diagnosis', 'ESI', 'Maps: bed, arrival', 'Traps / teaching'], rows));
  L.push('## Maps', '', ...Object.values(SCENARIOS).map((sc) => `- [${t(sc.title)}](maps.md#${anchor(sc.title)}): ${t(sc.subtitle)}; shift ${sc.shiftStart}, ${sc.durationMin} min, ${plural(sc.patients.length, 'patient')}, ${plural(sc.errors.length, 'staff error')}`), '');
  const unregistered = [...caseSourceFiles().entries()].filter(([id]) => !CASES[id]).map(([id, file]) => `\`${file}\` (\`${id}\`)`);
  const checks = ctxs.filter((x) => x.warnings.length).map((x) => `- [${code(x.c.id)}](${x.c.id}.md#content-checks): ${plural(new Set(x.warnings).size, 'content check')}`);
  if (unregistered.length) checks.push(`- Not registered in \`CASES\` (content/scenarios.ts), so no sheet: ${unregistered.join(', ')}`);
  if (checks.length) L.push('## Content checks', '', ...checks, '');
  return `${L.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

